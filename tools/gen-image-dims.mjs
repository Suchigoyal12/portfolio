// Regenerates src/site/image-dims.js from the real files in public/.
//
// Why a generated map rather than width/height typed into each <img>: the
// numbers have to match the files exactly or they introduce the very layout
// shift they exist to prevent, and 30-odd hand-copied pairs drift the first
// time an asset is re-exported. Run this after changing anything in public/:
//
//   node tools/gen-image-dims.mjs
//
import { execFileSync } from "child_process";
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

// fileURLToPath, not URL.pathname: the repo path contains a space, and
// pathname hands back "Portfolio%202026".
const ROOT = path.join(path.dirname(fileURLToPath(import.meta.url)), "..");
const PUBLIC = path.join(ROOT, "public");
const OUT = path.join(ROOT, "src", "site", "image-dims.js");

const walk = (dir) => fs.readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
  const p = path.join(dir, e.name);
  return e.isDirectory() ? walk(p) : [p];
});

const files = walk(PUBLIC).filter((f) => /\.(png|jpe?g|webp)$/i.test(f)).sort();
const entries = [];
for (const f of files) {
  const out = execFileSync("sips", ["-g", "pixelWidth", "-g", "pixelHeight", f], { encoding: "utf8" });
  const w = +(out.match(/pixelWidth:\s*(\d+)/) || [])[1];
  const h = +(out.match(/pixelHeight:\s*(\d+)/) || [])[1];
  if (!w || !h) { console.error("  !! no dimensions for", f); continue; }
  entries.push([`/${path.relative(PUBLIC, f)}`, w, h]);
}

const body = entries.map(([k, w, h]) => `  ${JSON.stringify(k)}: [${w}, ${h}],`).join("\n");
fs.writeFileSync(OUT, `// GENERATED by tools/gen-image-dims.mjs - do not edit by hand.
// Intrinsic pixel dimensions of everything in public/, so every <img> can
// declare width/height and the browser can reserve its box before the bytes
// arrive. Without these each page reflows as images land, which is the most
// amateur-reading loading behaviour there is (roadmap item 7).
//
// Re-run the generator after adding or re-exporting any image.

const DIMS = {
${body}
};

// Spread onto an <img>: <img src={src} {...dims(src)} />
// Returns nothing for an unknown src, so a missing entry degrades to today's
// behaviour rather than rendering a wrongly-sized box.
export function dims(src) {
  if (!src) return {};
  const d = DIMS[String(src).split("?")[0]];
  return d ? { width: d[0], height: d[1] } : {};
}

export default DIMS;
`);
console.log(`wrote ${entries.length} entries to ${path.relative(ROOT, OUT)}`);
